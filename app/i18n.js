function syncA11yLabels() {
  const langToggleBtn = safe("lang-toggle");
  if (langToggleBtn) langToggleBtn.setAttribute("aria-label", t("languageAria") || "Change language");

  if (isReal(state.dom.barWrapper)) state.dom.barWrapper.setAttribute("aria-label", t("strengthAria"));

  if (state.dom.resetBtn) state.dom.resetBtn.setAttribute("aria-label", t("resetAria"));

  if (state.dom.toggleVisibility && state.dom.input) {
    const isVisible = state.dom.input.type === "text";
    state.dom.toggleVisibility.setAttribute(
      "aria-label",
      isVisible ? t("hideAria") : t("showAria"),
    );
  }

  if (state.dom.copyBtn) state.dom.copyBtn.setAttribute("aria-label", t("copyBtnAria"));
}
